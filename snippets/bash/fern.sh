| キー     | 意味                          |
  | ------ | --------------------------- |
  | `?`    | 利用可能な mapping/action を表示    |
  | `a`    | action 入力プロンプトを開く           |
  | `.`    | 直前に `a` から実行した action を繰り返す |
  | `<CR>` | ファイルを開く / ディレクトリに入る         |
  | `l`    | ファイルを開く、ディレクトリなら展開          |
  | `h`    | ディレクトリを折りたたむ                |
  | `e`    | edit で開く                    |
  | `s`    | window selector で開く         |
  | `t`    | tab で開く                     |
  | `-`    | mark の toggle               |
  | `N`    | 新規ファイル作成                    |
  | `K`    | 新規ディレクトリ作成                  |
  | `c`    | copy                        |
  | `m`    | move                        |
  | `R`    | rename                      |
  | `D`    | trash                       |
  | `y`    | パスを yank                    |
  | `!`    | dotfile 表示/非表示              |
  | `fi`   | include filter              |
  | `fe`   | exclude filter              |
  | `z`    | drawer 幅を zoom              |
  | `Z`    | drawer 幅を reset             |

